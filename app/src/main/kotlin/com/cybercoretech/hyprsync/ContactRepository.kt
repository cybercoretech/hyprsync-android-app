// ContactRepository.kt – contact lookup; a stub until the encrypted DB DAO exists
package com.cybercoretech.hyprsync

import android.content.Context
import com.cybercoretech.hyprsync.data.Contact

object ContactRepository {
    private lateinit var appContext: Context

    /** Called once from [MyApplication]; the context is kept for the future DB layer. */
    fun init(context: Context) {
        appContext = context.applicationContext
    }

    private val dummy =
        Contact(
            id = 1,
            name = "Demo Contact",
            avatarUrl = null,
            notes = "Generated by the ContactRepository stub",
            tags = listOf("demo"),
            strength = 0.75f,
            lastInteraction = System.currentTimeMillis(),
        )

    fun getContactById(id: Long): Contact {
        // In a real implementation we would query the encrypted DB.
        return if (id == dummy.id) dummy else dummy.copy(id = id, name = "Contact $id")
    }
}
