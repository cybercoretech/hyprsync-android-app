/**
 * Simple QR‑share screen.
 * It receives a `contactId` (string), loads the Contact from the repository,
 * encodes the Contact as JSON, creates a QR code bitmap with ZXing, and shows it.
 * A “Save / Share” button is provided – implementation left as a stub because the
 * actual Android Intent code would be platform‑specific.
 */
@Composable
fun QRShareScreen(contactId: String) {
    // In a real app we would fetch from a DB; here we use a stub repository.
    val contact = remember(contactId) { ContactRepository.getContactById(contactId.toLongOrNull() ?: 0L) }

    // Encode contact to JSON – using kotlinx‑serialization for simplicity.
    val json = Json.encodeToString(contact)

    // Generate QR bitmap once.
    val qrBitmap = remember(json) { generateQrBitmap(json) }

    Column {
        Text(text = "QR Share for ${contact.name}")
        Spacer(modifier = Modifier.height(16.dp))
        if (qrBitmap != null) {
            Image(
                bitmap = qrBitmap.asImageBitmap(),
                contentDescription = "QR code for contact",
                modifier = Modifier.size(240.dp)
            )
        } else {
            Text("Failed to generate QR code")
        }
        Spacer(modifier = Modifier.height(24.dp))
        Button(onClick = {
            // TODO: implement Android share Intent to export the bitmap or JSON file.
        }) {
            Text("Save / Share")
        }
    }
}

/** Generates a QR code bitmap from the given text. Returns null on failure. */
private fun generateQrBitmap(text: String, size: Int = 512): Bitmap? {
    return try {
        val bitMatrix: BitMatrix = MultiFormatWriter().encode(text, BarcodeFormat.QR_CODE, size, size)
        val width = bitMatrix.width
        val height = bitMatrix.height
        val bmp = Bitmap.createBitmap(width, height, Bitmap.Config.RGB_565)
        for (x in 0 until width) {
            for (y in 0 until height) {
                bmp.setPixel(x, y, if (bitMatrix.get(x, y)) android.graphics.Color.BLACK else android.graphics.Color.WHITE)
            }
        }
        bmp
    } catch (e: Exception) {
        e.printStackTrace()
        null
    }
}

/** Very small stub repository – replace with real SQLCipher DAO later. */
object ContactRepository {
    private val dummy = Contact(
        id = 1,
        name = "Demo Contact",
        avatarUrl = null,
        notes = "Generated by QRShareScreen stub",
        tags = listOf("demo"),
        strength = 0.75f,
        lastInteraction = System.currentTimeMillis()
    )

    fun getContactById(id: Long): Contact {
        // In a real implementation we would query the encrypted DB.
        return if (id == dummy.id) dummy else dummy.copy(id = id, name = "Contact $id")
    }
}


