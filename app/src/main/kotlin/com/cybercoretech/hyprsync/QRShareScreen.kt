/**
 * Simple data class used for demonstration. In a real app you would fetch the
 * full Contact object from the encrypted DB.
 */
private data class DemoContact(val id: Long, val name: String)

private fun generateQrBitmap(text: String, size: Int = 256): Bitmap {
    val bitMatrix: BitMatrix = MultiFormatWriter().encode(text, BarcodeFormat.QR_CODE, size, size)
    val bitmap = Bitmap.createBitmap(size, size, Bitmap.Config.ARGB_8888)
    for (x in 0 until size) {
        for (y in 0 until size) {
            bitmap.setPixel(x, y, if (bitMatrix.get(x, y)) Color.CYAN else Color.TRANSPARENT)
        }
    }
    return bitmap
}

@Composable
fun QRShareScreen(contactId: String) {
    // In a real implementation you would look up the Contact by ID.
    val contact = remember { DemoContact(contactId.toLongOrNull() ?: 0L, "Contact #$contactId") }
    val json = "{\"id\":${contact.id},\"name\":\"${contact.name}\"}"
    val qrBitmap = remember { generateQrBitmap(json) }

    Scaffold(
        topBar = {
            CenterAlignedTopAppBar(title = { Text("QR Share – ${contact.name}") })
        }
    ) { padding ->
        Column(
            modifier = Modifier
                .fillMaxSize()
                .padding(padding)
                .padding(24.dp),
            verticalArrangement = Arrangement.Center,
            horizontalAlignment = androidx.compose.ui.Alignment.CenterHorizontally
        ) {
            Image(
                bitmap = qrBitmap.asImageBitmap(),
                contentDescription = "QR code for contact",
                modifier = Modifier.size(256.dp)
            )
            Spacer(modifier = Modifier.height(16.dp))
            Text(text = "Scan to import contact data", style = MaterialTheme.typography.bodyMedium)
        }
    }
}
